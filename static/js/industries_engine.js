window.splitSk = function splitSk(s) {
    var out=[], cur='', d=0;
    s.split('').forEach(function(ch) {
        if(ch==='(')d++;
        if(ch===')')d--;
        if(!d&&(ch===','||ch===';')){out.push(cur);cur=''}
        else cur+=ch
    });
    out.push(cur);
    return out.map(function(x) {
        x=x.trim().replace(/^(and|or) /,'');
        return x.charAt(0).toUpperCase()+x.slice(1);
    }).filter(Boolean);
};

window.CAREER_BUDDY_INDUSTRIES = (function() {
    var dn = { tech: 0, nt: 0, it: 0 };
    return window.DEPTS.map(function (d) {
        var k = dn[d.c]++;
        var key = d.c + '-' + (k + 1);
        return {
            category: d.c,
            icon: d.i,
            name: d.n,
            key: key,
            roles: d.r.map(function (item, j) {
                return {
                    name: item[0],
                    skills: window.splitSk(item[1]),
                    key: key + '-' + (j + 1)
                };
            })
        };
    });
})();

